package oleborn.analyticsservice.service;

import java.time.Instant;

/**
 * Сервис для обновления read‑модели {@code order_lifecycle} на основе событий из Kafka.
 * <p>
 * Каждый метод соответствует определённому типу события и обновляет соответствующее поле
 * (или поля) в таблице с использованием паттерна UPSERT.
 * <p>
 * Все методы идемпотентны и устойчивы к неупорядоченным событиям (out‑of‑order delivery)
 * за счёт сравнения временных меток внутри SQL-запросов.
 */
public interface OrderLifecycleService {

    /**
     * Обрабатывает событие OrderCreatedEvent – заказ создан.
     * <p>
     * Устанавливает время создания заказа (created_at) в read‑модели.
     * <p>
     * Если запись с данным order_id ещё не существует – создаётся новая строка.
     * Если запись уже есть, поле created_at обновляется только если новое значение
     * имеет более позднюю временную метку, чем существующее.
     * Это защищает от перезаписи более новых данных более старыми событиями.
     *
     * @param orderId   идентификатор заказа (первичный ключ таблицы)
     * @param createdAt время создания заказа (из события)
     */
    void upsertCreatedAt(Long orderId, Instant createdAt);

    /**
     * Обрабатывает событие PaymentStartedEvent – начата обработка платежа.
     * <p>
     * Устанавливает время начала обработки платежа (payment_started_at).
     * <p>
     * Аналогично upsertCreatedAt, но с защитой от NULL (используется COALESCE
     * на уровне SQL, чтобы корректно обрабатывать первое обновление поля).
     *
     * @param orderId    идентификатор заказа
     * @param startedAt  время начала обработки платежа
     */
    void upsertPaymentStartedAt(Long orderId, Instant startedAt);

    /**
     * Обрабатывает событие PaymentCompletedEvent – платёж успешно завершён.
     * <p>
     * Устанавливает время завершения платежа (payment_completed_at) и статус платежа (payment_status).
     * <p>
     * Важно: оба поля обновляются атомарно и только в том случае, если новое время завершения
     * является более поздним, чем существующее (или поле ещё не заполнено).
     * Это гарантирует, что статус всегда соответствует самому последнему событию завершения.
     * <p>
     * Если запись отсутствует – создаётся новая строка с указанными данными.
     *
     * @param orderId      идентификатор заказа
     * @param completedAt  время завершения платежа
     * @param status       статус платежа (например, "PAID")
     */
    void upsertPaymentCompletedAt(Long orderId, Instant completedAt, String status);

    /**
     * Обрабатывает событие NotificationSentEvent – уведомление отправлено.
     * <p>
     * Устанавливает время отправки уведомления (notification_sent_at).
     * <p>
     * Аналогично другим upsert-методам: обновляет поле только если новое значение
     * имеет более позднюю временную метку, предотвращая перезапись более новых данных.
     *
     * @param orderId  идентификатор заказа
     * @param sentAt   время отправки уведомления
     */
    void upsertNotificationSentAt(Long orderId, Instant sentAt);
}